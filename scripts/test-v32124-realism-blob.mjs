// Runtime minimo: le articolazioni devono cambiare posa durante il galoppo.
const motionStart=js.indexOf('function rotateHorsePart');
const motionEnd=js.indexOf('function top3Rankings',motionStart);
assert.ok(motionStart>=0&&motionEnd>motionStart);
const motionBlock=js.slice(motionStart,motionEnd);
const motionFactory=new Function(`${motionBlock}; return {animateHorseMotion};`);
const {animateHorseMotion}=motionFactory();
const style=()=>({transform:'',opacity:'',setProperty(){}});
const part=()=>({style:style()});
const lower=()=>({style:style()});
const mkLeg=()=>({upper:part(),lower:lower()});
const motion={core:part(),body:part(),neck:part(),head:part(),jockey:part(),tail:part(),shadow:part(),legs:{'hind-near':mkLeg(),'hind-far':mkLeg(),'front-near':mkLeg(),'front-far':mkLeg()}};
const item={motion,index:0,strideMs:300};
animateHorseMotion(item,100,0.002,0.2,{gaitPower:.95,headMotion:.9});
const poseA=motion.legs['front-near'].upper.style.transform;
animateHorseMotion(item,220,0.002,0.4,{gaitPower:.95,headMotion:.9});
const poseB=motion.legs['front-near'].upper.style.transform;
assert.notEqual(poseA,poseB,'la zampa anteriore deve articolarsi tra due fasi del galoppo');
assert.match(motion.core.style.transform,/translateY/);

